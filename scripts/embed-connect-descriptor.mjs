import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const checkOnly = process.argv.includes("--check");
const rootArgument = process.argv.indexOf("--root");
const sdkRoot =
  rootArgument === -1
    ? path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
    : path.resolve(process.argv[rootArgument + 1] ?? "");
if (rootArgument !== -1 && !process.argv[rootArgument + 1]) {
  throw new Error("--root requires a path");
}
let stale = false;

const descriptors = [
  {
    descriptor: "proto/external-ingestion-v1.descriptor.binpb",
    output: "src/connect-descriptor.ts",
    constant: "CONNECT_DESCRIPTOR_BASE64",
    functionName: "connectDescriptorBytes",
  },
];

for (const item of descriptors) {
  const descriptorPath = path.join(sdkRoot, item.descriptor);
  const outputPath = path.join(sdkRoot, item.output);
  const base64 = readFileSync(descriptorPath).toString("base64");
  const chunks = base64.match(/.{1,96}/g) ?? [];

  const source = `// Generated by pnpm proto:descriptor. Do not edit manually.
import { Buffer } from "node:buffer";

const ${item.constant} = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join("");

export function ${item.functionName}(): Uint8Array {
  return new Uint8Array(Buffer.from(${item.constant}, "base64"));
}
`;

  if (checkOnly) {
    if (readFileSync(outputPath, "utf8") !== source) {
      console.error(`${item.output} is stale`);
      stale = true;
    }
  } else {
    writeFileSync(outputPath, source);
  }
}

if (stale) {
  process.exitCode = 1;
}
