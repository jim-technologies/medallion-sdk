import { readFileSync, writeFileSync } from "node:fs";

const checkOnly = process.argv.includes("--check");
let stale = false;

const descriptors = [
  {
    descriptor: "../proto/medallion-connect.descriptor.binpb",
    output: "../src/connect-descriptor.ts",
    constant: "CONNECT_DESCRIPTOR_BASE64",
    functionName: "connectDescriptorBytes",
  },
  {
    descriptor: "../proto/medallion-ontology.descriptor.binpb",
    output: "../src/ontology-descriptor.ts",
    constant: "ONTOLOGY_DESCRIPTOR_BASE64",
    functionName: "ontologyDescriptorBytes",
  },
  {
    descriptor: "../proto/medallion-storage.descriptor.binpb",
    output: "../src/storage-descriptor.ts",
    constant: "STORAGE_DESCRIPTOR_BASE64",
    functionName: "storageDescriptorBytes",
  },
];

for (const item of descriptors) {
  const descriptorUrl = new URL(item.descriptor, import.meta.url);
  const outputUrl = new URL(item.output, import.meta.url);
  const base64 = readFileSync(descriptorUrl).toString("base64");
  const chunks = base64.match(/.{1,96}/g) ?? [];

  const source = `// Generated by pnpm proto:descriptor. Do not edit manually.
import { Buffer } from "node:buffer";

const ${item.constant} = [
${chunks.map((chunk) => `  "${chunk}",`).join("\n")}
].join("");

export function ${item.functionName}(): Uint8Array {
  return new Uint8Array(Buffer.from(${item.constant}, "base64"));
}
`;

  if (checkOnly) {
    if (readFileSync(outputUrl, "utf8") !== source) {
      console.error(`${item.output.replace("../", "")} is stale`);
      stale = true;
    }
  } else {
    writeFileSync(outputUrl, source);
  }
}

if (stale) {
  process.exitCode = 1;
}
